import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdtemp, mkdir, writeFile, readFile, cp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { build } from 'esbuild';
import { chromium } from 'playwright-core';
import { buildBrowserStorageRuntime } from './browser-storage-runtime.mjs';

test('a fresh MV3 installation saves, finds and reads an actual page before any provider, native or download request', { timeout: 45000 }, async testContext => {
  const directory = await mkdtemp(path.join(tmpdir(), 'web-recall-onboarding-contract-'));
  let context, server;
  testContext.after(async () => { await context?.close(); if (server) await new Promise(resolve => server.close(resolve)); await rm(directory, { recursive: true, force: true }); });
  const manifest = JSON.parse(await readFile('manifest.json', 'utf8'));
  const bundles = await Promise.all(['ui/sidepanel/index.ts', 'content/index.ts'].map(entry => build({ entryPoints: [path.join('src', entry)], bundle: true, write: false, format: 'esm', platform: 'browser', target: 'es2022', logLevel: 'silent' })));
  const watchModels = 'globalThis.onboardingCalls={http:[],native:0}; globalThis.fetch=async(input)=>{globalThis.onboardingCalls.http.push(String(input));throw Error("No model service available in the isolated onboarding test");}; chrome.runtime.connectNative=()=>{globalThis.onboardingCalls.native++;throw Error("No native companion installed in the isolated test");};\n';
  await buildBrowserStorageRuntime(directory, watchModels);
  await writeFile(path.join(directory, 'ui.js'), bundles[0].outputFiles[0].text);
  await mkdir(path.join(directory, 'dist/beta/ui'), { recursive: true });
  await writeFile(path.join(directory, 'dist/beta/content.js'), bundles[1].outputFiles[0].text);
  await cp('src/assets', path.join(directory, 'dist/beta/assets'), { recursive: true });
  await writeFile(path.join(directory, 'dist/beta/ui/index.html'), '<!doctype html><title>Web Recall onboarding contract</title><div id="app-root" data-view="sidepanel"></div><script type="module" src="../../../ui.js"></script>');
  const { manifest_version, minimum_chrome_version, version, permissions, optional_permissions, background, content_security_policy,
    cross_origin_embedder_policy, cross_origin_opener_policy } = manifest;
  await writeFile(path.join(directory, 'manifest.json'), JSON.stringify({ manifest_version, minimum_chrome_version, version, permissions, optional_permissions, background,
    content_security_policy, cross_origin_embedder_policy, cross_origin_opener_policy, name: 'Web Recall onboarding contract',
    host_permissions: ['http://127.0.0.1/*', 'http://localhost:11434/*'], side_panel: { default_path: 'dist/beta/ui/index.html' }, action: { default_title: 'Web Recall contract' },
    content_scripts: [{ matches: ['http://127.0.0.1/*'], js: ['dist/beta/content.js'], run_at: 'document_idle' }] }));
  server = createServer((_request, response) => {
    response.setHeader('Content-Type', 'text/html');
    response.end('<!doctype html><title>Coastal field notes</title><article><h1>Coastal field notes</h1><p>Copper terns migrate along the coast. Their nests sit above the high tide line.</p><h2>Observations</h2><p>These field notes compare nesting sites and seasonal migration.</p></article>');
  });
  await new Promise((resolve, reject) => { server.once('error', reject); server.listen(0, '127.0.0.1', resolve); });
  context = await chromium.launchPersistentContext(path.join(directory, 'profile'), { channel: 'chromium', headless: true, timeout: 10000, viewport: { width: 420, height: 900 }, args: [`--disable-extensions-except=${directory}`, `--load-extension=${directory}`] });
  const worker = context.serviceWorkers()[0] || await context.waitForEvent('serviceworker', { timeout: 10000 });
  const source = await context.newPage(), articleUrl = `http://127.0.0.1:${server.address().port}/article`;
  await source.goto(articleUrl);
  const ui = await context.newPage(); ui.setDefaultTimeout(10000);
  const extensionId = new URL(worker.url()).host;
  const panelUrl = `chrome-extension://${extensionId}/dist/beta/ui/index.html`;
  await ui.goto(panelUrl);
  await ui.locator('.wr-empty-memory').waitFor();
  assert.match(await ui.locator('.wr-empty-memory').textContent(), /No model setup needed/);
  await ui.locator('#beta-keep-manual-capture').click();
  await source.bringToFront();
  await ui.evaluate(() => document.querySelector('.wr-empty-memory .primary-button').click());
  await ui.waitForFunction(() => document.querySelector('#beta-recall-setup').hidden === false);
  await ui.bringToFront();
  assert.equal(await ui.locator('#beta-recall-heading').textContent(), 'Find your saved page');
  await ui.locator('#beta-search-input').fill('Copper terns');
  await ui.locator('#beta-search-input').press('Enter');
  await ui.waitForFunction(() => document.querySelector('#beta-recall-heading').textContent === 'Read what you saved');
  await source.goto('about:blank');
  await ui.bringToFront();
  await ui.locator('#beta-recall-next').click();
  await ui.locator('.saved-reader-text').waitFor();
  assert.match(await ui.locator('.saved-reader-text').textContent(), /Copper terns migrate along the coast/);
  assert.equal(await ui.locator('.saved-reader-text mark').textContent(), 'Copper terns');
  assert.equal(await ui.locator('#beta-ask-results').isVisible(), false);
  assert.equal(await ui.locator('#beta-search-results .ask-this-page').isVisible(), false);
  assert.equal(await ui.locator('.ask-this-page:visible').count(), 0);
  assert.equal(await ui.locator('#beta-ask-memory').evaluate(button => button.hidden), true);
  await ui.locator('#beta-optional-ai').waitFor();
  const state = await ui.evaluate(() => chrome.runtime.sendMessage({ type: 'GET_SETTINGS' }));
  assert.equal(state.settings.paused, true); assert.equal(state.settings.automaticAi, false); assert.equal(state.settings.recallSetupComplete, true);
  assert.deepEqual(await worker.evaluate(() => globalThis.onboardingCalls), { http: [], native: 0 });
  assert.equal(await worker.evaluate(async () => (await chrome.storage.local.get('savedLibraryAuthority')).savedLibraryAuthority?.retired), true);
  const rows = await ui.evaluate(() => chrome.runtime.sendMessage({ type: 'GET_PAGE_LIST' }));
  assert.equal(rows.pages[0].url, articleUrl); assert.equal(rows.pages[0].hasEmbeddings, false); assert.equal(rows.pages[0].hasSummary, false);
  assert.deepEqual((await ui.evaluate(() => chrome.runtime.sendMessage({ type: 'GET_PROCESSING' }))).queue, []);
  await ui.evaluate(() => document.querySelector('a[data-view="manage"]').click());
  await ui.locator('#manage-count').filter({ hasText: '1 page' }).waitFor();
  await ui.getByRole('link', { name: 'Backups', exact: true }).click();
  await ui.getByRole('button', { name: 'Save unencrypted backup' }).waitFor();
  await ui.waitForFunction(() => document.querySelector('#manage-storage-usage').textContent.startsWith('Estimated usage:'));
  const storage = await ui.evaluate(() => navigator.storage.estimate());
  assert.ok(Number.isFinite(storage.usage) && storage.usage > 0, 'The real extension origin reports saved storage');
  assert.match(await ui.locator('#manage-storage-usage').textContent(), /\d.*(?:B|KiB|MiB|GiB|TiB)/);
  await ui.evaluate(() => document.querySelector('a[data-view="manage"]').click());
  await ui.locator('summary').filter({ hasText: /^Page actions$/u }).click();
  await ui.locator('#manage-forget > summary').click();
  assert.equal(await ui.locator('#manage-forget-site').isVisible(), true);
  assert.equal(await ui.locator('#manage-forget-confirmation').isVisible(), false);
  assert.equal((await ui.evaluate(() => chrome.runtime.sendMessage({ type: 'GET_PAGE_LIST' }))).pages.length, 1);
  assert.deepEqual(await worker.evaluate(() => globalThis.onboardingCalls), { http: [], native: 0 });
  await ui.locator('#beta-view-manage .utility-back').click();
  await ui.locator('#beta-setup-ai').click();
  assert.equal(await ui.locator('#settings-models').getAttribute('open'), '');
  assert.equal(await ui.locator('#beta-automatic-ai').isChecked(), false);
  await ui.locator('#settings-models details > summary').filter({ hasText: /^Chat provider$/u }).click();
  const provider = ui.locator('#beta-provider-select');
  await ui.waitForFunction(() => Array.from(document.querySelector('#beta-provider-select').options).some(option => option.value === 'ollama'));
  assert.equal(await provider.locator(':checked').textContent(), 'Disabled');
  assert.equal(await ui.locator('#beta-chat-provider-fields').isVisible(), false);
  assert.deepEqual(await worker.evaluate(() => globalThis.onboardingCalls), { http: [], native: 0 });
  await provider.selectOption('ollama');
  await ui.locator('#beta-provider-status').filter({ hasText: /Offline/ }).waitFor();
  assert.match(await ui.locator('#beta-provider-status').textContent(), /Offline/);
  const callsAfterOpeningModels = await worker.evaluate(() => globalThis.onboardingCalls.http.length);
  assert.ok(callsAfterOpeningModels > 0, 'The explicit chat-provider choice allows discovery');
  await ui.locator('#beta-view-settings .utility-back').click();
  await ui.getByRole('button', { name: 'Ask these pages' }).waitFor();
  await ui.close();
  const reopened = await context.newPage(); await reopened.goto(panelUrl);
  await reopened.waitForFunction(() => document.querySelector('#beta-recents-list > article'));
  assert.equal(await reopened.locator('#beta-recall-setup').isVisible(), false); assert.equal(await reopened.locator('#beta-optional-ai').isVisible(), false);
  assert.equal(await worker.evaluate(() => globalThis.onboardingCalls.http.length), callsAfterOpeningModels);
  testContext.diagnostic(JSON.stringify({ browser: context.browser().version(), savedPages: rows.pages.length, beforeOptionalSetup: { providerCalls: 0, nativeCalls: 0 } }));
});
